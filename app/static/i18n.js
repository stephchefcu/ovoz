let LANG = "uz";
try { LANG = localStorage.getItem("lang") || "uz"; } catch (e) {}
if (!I18N[LANG]) LANG = "uz";

function t(key) { return (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key; }

function applyLang() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll(".lang button").forEach(b => b.classList.toggle("on", b.dataset.l === LANG));
  // Department names: <x data-name-en="..." data-name-uz="..." data-name-ru="..."> shows the current language
  const key = "name" + LANG.charAt(0).toUpperCase() + LANG.slice(1);
  document.querySelectorAll("[data-name-en]").forEach(el => { el.textContent = el.dataset[key] || el.dataset.nameEn; });
  // Whole blocks per language (Terms & privacy page)
  document.querySelectorAll("[data-lang-block]").forEach(el => el.classList.toggle("hidden", el.dataset.langBlock !== LANG));
  document.dispatchEvent(new Event("langchange"));
}

function setLang(l) {
  LANG = l;
  try { localStorage.setItem("lang", l); } catch (e) {}
  applyLang();
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang button").forEach(b => b.addEventListener("click", () => setLang(b.dataset.l)));
  applyLang();
});
